// Generates the deploy root's compose files from deploy manifests (design §7.3, D11):
// one fragment per app (<app>/compose.yaml) and a root compose.yaml that only includes them.
// Pure: manifests and the environment's settings in, file contents out. Nobody edits the output.

import { toYaml, type Yaml } from "./yaml.ts";

export interface Manifest {
  v: 1;
  app: string;
  appliesFrom: string;
  release?: { repo: string; tag: string; manifest: "release.json" | "package.json" };
  bundle?: { kind: "release-asset"; repo: string; asset: string; checksums?: string };
  components: Component[];
  env?: { file: string; schema?: string; template?: string; secrets?: string[] };
}

export type Source =
  | { kind: "public-registry"; image: string }
  | { kind: "company-registry"; registry: string; image: string; tag?: string; build?: { repo: string; tag: string; script: string; platform?: string } };

interface Port { container: number; host?: number; name?: string }
interface Volume { target: string; path?: string; file?: string }

export interface Component {
  id: string;
  type: string;
  dependsOn?: string[];
  service?: string;
  source?: Source;
  ports?: Port[];
  volumes?: Volume[];
  environment?: Record<string, string>;
  envFile?: boolean;
  health?: "image" | "none" | string[];
  command?: string[];
  init?: boolean;
  stopGracePeriod?: string;
  extraHosts?: string[];
  compose?: Record<string, Yaml>;
}

/** One environment's settings (UAT or PROD): what the Deployer keeps as desired state. */
export interface Environment {
  name: string;
  /** Compose project name. */
  project: string;
  /** Address every published port binds to. */
  bindIp: string;
  /** Registered registries (D13): name -> image prefix. */
  registries: Record<string, string>;
  /** D27, opt-in (phase 7): a version newer than its manifest deploys only after its version assessment was adopted. */
  requireEvaluation?: boolean;
  /** D35: the machines of this environment, each running an executor. None: one machine called "local". */
  hosts?: Record<string, HostSettings>;
  /** D36: the environment's one DNS name; apps behind nginx are https://<domain>:<port>. */
  domain?: string;
  /** D36: where the certificate sits on the nginx host, for the recommended configuration. */
  nginx?: { certificate?: string; certificateKey?: string };
  apps: Record<string, {
    version: string;
    /** D35: the host this app runs on (placed per app); the first host when absent. */
    host?: string;
    /** D36: how other apps and people reach it; absent: not reachable from outside its host. */
    ingress?: Ingress;
    /** D36: false keeps the internal CA out of this app's containers. */
    ca?: boolean;
    /** PROD only: hours the same digest must have run in UAT before it may be promoted (§6.2, D15); 0 when absent. */
    uatSoakHours?: number;
    /** Per-component overrides: host port by container port, host path by container path. */
    overrides?: Record<string, { ports?: Record<string, number>; volumes?: Record<string, string> }>;
    /** Per-component settings of this environment for the Deployer's drivers (phase 5): the Studio graph name, the OMA model, … */
    settings?: Record<string, Record<string, string>>;
  }>;
}

/**
 * D35: one machine. address: how other machines and nginx reach it; bindIp: where its published ports bind;
 * project: its compose project when it is not the environment's (two simulated hosts on one Docker).
 */
export interface HostSettings { address: string; bindIp?: string; project?: string }

/**
 * D36: nginx terminates HTTPS at https://<domain>:<port> (port 443: no port; path: under that origin, the Deployer
 * at /deploy/) and forwards to the component's published port on the app's host; direct is http://<host address>:<port>.
 * component / containerPort pick the published port; the app's first published port when absent.
 */
export type Ingress =
  | { kind: "nginx"; port: number; path?: string; component?: string; containerPort?: number; maxBodySize?: string }
  | { kind: "direct"; component?: string; containerPort?: number };

export interface GeneratedFiles { [path: string]: string }

/** D36: where the internal CA is mounted in every container when the administrator configured one. */
export const CA_PATH = "/etc/open-atlas/ca.pem";

export interface GenerateOptions {
  /** Resolves {{app:<id>.url}} in a component's environment values. */
  resolve?: (text: string) => string;
  /** The internal CA is configured: mount ./ca/ca.pem and point Node at it (NODE_EXTRA_CA_CERTS adds, never replaces). */
  ca?: boolean;
}

const HEADER = "Generated by Open Atlas Deployer from the app's deploy manifest. Do not edit: change the manifest.";
const LOGGING: Yaml = { driver: "local", options: { "max-size": "50m", "max-file": "3" } };

export class ManifestError extends Error {}

export function imageRef(source: Source, version: string, env: Environment): string {
  if (source.kind === "public-registry") return source.image;
  const prefix = env.registries[source.registry];
  if (!prefix) throw new ManifestError(`registry ${source.registry} is not registered`);
  return `${prefix}/${source.image}:${(source.tag ?? "{version}").replaceAll("{version}", version)}`;
}

function merge(base: Record<string, Yaml>, extra: Record<string, Yaml>): Record<string, Yaml> {
  const out = { ...base };
  for (const [k, v] of Object.entries(extra)) {
    const b = out[k];
    out[k] = b && typeof b === "object" && !Array.isArray(b) && v && typeof v === "object" && !Array.isArray(v) ? merge(b, v) : v;
  }
  return out;
}

function service(manifest: Manifest, c: Component, env: Environment, options: GenerateOptions = {}): Record<string, Yaml> {
  const app = env.apps[manifest.app];
  const over = app.overrides?.[c.id] ?? {};
  const byId = new Map(manifest.components.map((x) => [x.id, x]));
  const deps = (c.dependsOn ?? []).map((id) => byId.get(id)!).filter((d) => d.type === "compose-service");
  const s: Record<string, Yaml> = {
    image: imageRef(c.source!, app.version, env),
    restart: "unless-stopped",
    labels: { "org.open-atlas.app": manifest.app, "org.open-atlas.component": c.id, "org.open-atlas.version": app.version },
  };
  if (c.init) s.init = true;
  if (c.command) s.command = c.command;
  if (c.stopGracePeriod) s.stop_grace_period = c.stopGracePeriod;
  if (deps.length) s.depends_on = Object.fromEntries(deps.map((d) => [d.service!, { condition: (d.health ?? "image") === "none" ? "service_started" : "service_healthy" }]));
  if (c.envFile && manifest.env) s.env_file = [`../${manifest.env.file}`];
  const ca = options.ca && app.ca !== false;
  const environment: Record<string, string> = { ...(ca ? { NODE_EXTRA_CA_CERTS: CA_PATH } : {}), ...Object.fromEntries(Object.entries(c.environment ?? {}).map(([k, v]) => [k, options.resolve ? options.resolve(v) : v])) };
  if (Object.keys(environment).length) s.environment = environment;
  const ports = (c.ports ?? []).flatMap((p) => {
    const host = over.ports?.[String(p.container)] ?? p.host;
    return host ? [`${env.bindIp}:${host}:${p.container}`] : [];
  });
  if (ports.length) s.ports = ports;
  const volumes = [...(c.volumes ?? []).map((v) => v.file
    ? `./files/${v.file}:${v.target}:ro`
    : `${over.volumes?.[v.target] ?? `./${v.path}`}:${v.target}`), ...(ca ? [`./ca/ca.pem:${CA_PATH}:ro`] : [])];
  if (volumes.length) s.volumes = volumes;
  if (c.extraHosts) s.extra_hosts = c.extraHosts;
  if (Array.isArray(c.health)) s.healthcheck = { test: c.health, interval: "10s", timeout: "5s", retries: 30 };
  s.logging = LOGGING;
  return c.compose ? merge(s, c.compose) : s;
}

export function generate(manifests: Manifest[], env: Environment, options: GenerateOptions = {}): GeneratedFiles {
  const files: GeneratedFiles = {};
  const owners = new Map<string, string>();
  const claim = (what: string, owner: string) => {
    const prior = owners.get(what);
    if (prior && prior !== owner) throw new ManifestError(`${what} is used by both ${prior} and ${owner}`);
    owners.set(what, owner);
  };
  const include: Yaml[] = [];
  for (const m of [...manifests].sort((a, b) => a.app.localeCompare(b.app))) {
    if (!env.apps[m.app]) continue;
    const services: Record<string, Yaml> = {};
    for (const c of m.components.filter((x) => x.type === "compose-service")) {
      claim(`service ${c.service}`, `${m.app}/${c.id}`);
      const s = service(m, c, env, options);
      for (const p of (s.ports as string[] | undefined) ?? []) claim(`host port ${p.split(":").at(-2)}`, `${m.app}/${c.id}`);
      services[c.service!] = s;
    }
    if (!Object.keys(services).length) continue;
    files[`${m.app}/compose.yaml`] = toYaml({ services }, `${HEADER}\napp ${m.app} ${env.apps[m.app].version} (manifest from ${m.appliesFrom}), environment ${env.name}`);
    include.push(m.env ? { path: `${m.app}/compose.yaml`, env_file: m.env.file } : { path: `${m.app}/compose.yaml` });
  }
  files["compose.yaml"] = toYaml({ name: env.project, include }, `${HEADER}\nenvironment ${env.name}: one fragment per app (design §7.3)`);
  return files;
}
