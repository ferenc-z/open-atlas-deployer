#!/usr/bin/env bash
# Build the local NiFi lab under $LAB (default ~/nifi-lab), no sudo.
#
#   setup.sh            extract, make certs (once), configure every instance
#   setup.sh certs      only JDKs, ZooKeeper, toolkit, passwords and certificates
#   setup.sh all NAME...  only extract/configure those instances
#
# Expects the downloads from fetch.sh in $LAB/downloads. Safe to re-run:
# extraction and certificates are kept, configuration is rewritten.
# Instances must be stopped while it runs (lab.sh stop).
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$HERE/lab.conf"
DL="$LAB/downloads"
PY="python3 -I"
STAGE="${1:-all}"; shift || true
ONLY="${*:-$(instances)}"   # setup.sh all n200 ... limits to those instances

log() { echo "[setup] $*"; }

unzip_to() { # zip dest-parent
  $PY -m zipfile -e "$1" "$2"
}

# ---------- extract ----------
mkdir -p "$LAB/dist" "$LAB/jdk" "$LAB/instances" "$LAB/secrets"
chmod 700 "$LAB/secrets"
for v in 11 21; do
  if [ ! -e "$LAB/jdk/$v" ]; then
    log "extract JDK $v"
    d="$(mktemp -d "$LAB/jdk/x.XXXX")"
    tar -xzf "$DL/jdk$v.tar.gz" -C "$d"
    mv "$d"/* "$LAB/jdk/" && rmdir "$d"
    ln -s "$(ls -d "$LAB"/jdk/jdk-"$v"* | head -1)" "$LAB/jdk/$v"
  fi
done
if [ ! -d "$LAB/dist/zookeeper-$ZK_VERSION" ]; then
  log "extract ZooKeeper"
  tar -xzf "$DL/zookeeper-$ZK_VERSION.tar.gz" -C "$LAB/dist"
  mv "$LAB/dist/apache-zookeeper-$ZK_VERSION-bin" "$LAB/dist/zookeeper-$ZK_VERSION"
fi
if [ ! -d "$LAB/dist/nifi-toolkit-$TOOLKIT_VERSION" ]; then
  log "extract toolkit"
  unzip_to "$DL/nifi-toolkit-$TOOLKIT_VERSION.zip" "$LAB/dist"
  chmod +x "$LAB/dist/nifi-toolkit-$TOOLKIT_VERSION"/bin/*.sh
fi
[ "$STAGE" = certs ] || for v in $(for n in $ONLY; do inst_field "$n" 2; done | sort -u); do
  [ -d "$LAB/dist/nifi-$v" ] && continue
  log "extract NiFi $v"
  if [ -f "$DL/nifi-$v.tar.gz" ]; then tar -xzf "$DL/nifi-$v.tar.gz" -C "$LAB/dist"
  else unzip_to "$DL/nifi-$v.zip" "$LAB/dist"; fi
  chmod +x "$LAB/dist/nifi-$v"/bin/*.sh
done

# ---------- secrets ----------
SECRETS="$LAB/secrets/lab.env"
if [ ! -f "$SECRETS" ]; then
  log "generate passwords -> $SECRETS"
  rnd() { $PY -c 'import secrets;print(secrets.token_urlsafe(18))'; }
  umask 077
  cat > "$SECRETS" <<EOF
KEYSTORE_PASS=$(rnd)
TRUSTSTORE_PASS=$(rnd)
CLIENT_P12_PASS=$(rnd)
SENSITIVE_PROPS_KEY=$(rnd)
EOF
  umask 022
fi
. "$SECRETS"

# ---------- certificates (lab CA = tls-toolkit standalone) ----------
CERTS="$LAB/certs"
if [ ! -f "$CERTS/nifi-cert.pem" ]; then
  log "sign certificates with tls-toolkit $TOOLKIT_VERSION"
  hosts=$(for n in $(instances); do inst_field "$n" 5; done | paste -sd,)
  JAVA_HOME="$LAB/jdk/11" "$LAB/dist/nifi-toolkit-$TOOLKIT_VERSION/bin/tls-toolkit.sh" standalone \
    -o "$CERTS" -n "$hosts" --subjectAlternativeNames localhost,127.0.0.1 \
    -T PKCS12 -S "$KEYSTORE_PASS" -K "$KEYSTORE_PASS" -P "$TRUSTSTORE_PASS" \
    -C "$CLIENT_MONITOR" -C "$CLIENT_OPERATOR" -C "$CLIENT_NGINX" -B "$CLIENT_P12_PASS"
  chmod -R go-rwx "$CERTS"
fi
# PEM copies of the client certs for curl / python.
mkdir -p "$CERTS/pem"
for dn in "$CLIENT_MONITOR" "$CLIENT_OPERATOR" "$CLIENT_NGINX"; do
  cn="${dn%%,*}"; cn="${cn#CN=}"
  p12="$CERTS/$(echo "$dn" | sed 's/, /_/g').p12"
  [ -f "$CERTS/pem/$cn.key" ] && continue
  for legacy in "" "-legacy"; do
    if openssl pkcs12 $legacy -in "$p12" -passin "pass:$CLIENT_P12_PASS" -clcerts -nokeys -out "$CERTS/pem/$cn.crt" 2>/dev/null \
      && openssl pkcs12 $legacy -in "$p12" -passin "pass:$CLIENT_P12_PASS" -nocerts -nodes -out "$CERTS/pem/$cn.key" 2>/dev/null; then
      break
    fi
  done
  [ -s "$CERTS/pem/$cn.key" ] || { echo "cannot convert $p12" >&2; exit 1; }
done
cp "$CERTS/nifi-cert.pem" "$CERTS/pem/ca.crt"
chmod 600 "$CERTS"/pem/*.key
[ "$STAGE" = certs ] && { log "certs done in $CERTS"; exit 0; }

# ---------- ZooKeeper ----------
ZK="$LAB/zk"
mkdir -p "$ZK/conf" "$ZK/data" "$ZK/logs"
cp "$LAB/dist/zookeeper-$ZK_VERSION/conf/logback.xml" "$ZK/conf/" 2>/dev/null || true
cat > "$ZK/conf/zoo.cfg" <<EOF
tickTime=2000
initLimit=10
syncLimit=5
dataDir=$ZK/data
clientPort=$ZK_PORT
clientPortAddress=127.0.0.1
admin.enableServer=false
4lw.commands.whitelist=ruok,stat,srvr,mntr
EOF

# ---------- NiFi instances ----------
members=$(for n in $(instances); do [ "$(inst_field "$n" 6)" != "-" ] && echo "$n"; done)

write_authorizers() { # file node-identities...
  local f="$1"; shift
  {
    cat <<EOF
<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<!-- Generated by open-atlas-deployer dev/nifi-lab/setup.sh -->
<authorizers>
    <userGroupProvider>
        <identifier>file-user-group-provider</identifier>
        <class>org.apache.nifi.authorization.FileUserGroupProvider</class>
        <property name="Users File">$CREF/users.xml</property>
        <property name="Initial User Identity 1">$CLIENT_OPERATOR</property>
        <property name="Initial User Identity 2">$CLIENT_MONITOR</property>
        <property name="Initial User Identity 3">$CLIENT_NGINX</property>
EOF
    local i=4; for id in "$@"; do echo "        <property name=\"Initial User Identity $i\">$id</property>"; i=$((i+1)); done
    cat <<EOF
    </userGroupProvider>
    <accessPolicyProvider>
        <identifier>file-access-policy-provider</identifier>
        <class>org.apache.nifi.authorization.FileAccessPolicyProvider</class>
        <property name="User Group Provider">file-user-group-provider</property>
        <property name="Authorizations File">$CREF/authorizations.xml</property>
        <property name="Initial Admin Identity">$CLIENT_OPERATOR</property>
EOF
    i=1; for id in "$@"; do echo "        <property name=\"Node Identity $i\">$id</property>"; i=$((i+1)); done
    cat <<EOF
    </accessPolicyProvider>
    <authorizer>
        <identifier>managed-authorizer</identifier>
        <class>org.apache.nifi.authorization.StandardManagedAuthorizer</class>
        <property name="Access Policy Provider">file-access-policy-provider</property>
    </authorizer>
</authorizers>
EOF
  } > "$f"
}

for n in $ONLY; do
  ver=$(inst_field "$n" 2); jdk=$(inst_field "$n" 3); port=$(inst_field "$n" 4)
  cn=$(inst_field "$n" 5); proto=$(inst_field "$n" 6); lb=$(inst_field "$n" 7)
  dir="$LAB/instances/$n"
  if [ ! -d "$dir" ]; then
    log "create instance $n from nifi-$ver"
    cp -a "$LAB/dist/nifi-$ver" "$dir"
  fi
  log "configure $n (NiFi $ver, JDK $jdk, https $port)"
  conf=$(inst_conf "$n"); data=$(inst_data "$n"); boot="$dir/conf/bootstrap.conf"
  # Paths written into the configuration: relative to the installation (NiFi's working directory) as shipped, or
  # absolute for a split instance (lab.conf SPLIT_INSTANCES).
  CREF=./conf
  if is_split "$n"; then
    CREF="$conf"
    mkdir -p "$conf" "$data"
    if [ ! -f "$conf/nifi.properties" ]; then
      log "move $n's configuration to $conf (bootstrap.conf stays in $dir/conf, where nifi.sh reads it)"
      for f in "$dir/conf"/*; do [ "$(basename "$f")" = bootstrap.conf ] || mv "$f" "$conf/"; done
    fi
    for r in flowfile_repository content_repository provenance_repository database_repository state; do
      if [ -e "$dir/$r" ] && [ ! -e "$data/$r" ]; then log "move $dir/$r to $data"; mv "$dir/$r" "$data/"; fi
    done
    $PY "$HERE/props.py" "$boot" "conf.dir=$conf" "notification.services.file=$conf/bootstrap-notification-services.xml"
  fi
  ks=$(ls "$CERTS/$cn"/keystore.* | head -1); ts=$(ls "$CERTS/$cn"/truststore.* | head -1)
  cp "$ks" "$conf/"; cp "$ts" "$conf/"
  kst=$(case "$ks" in *.p12|*.pkcs12) echo PKCS12;; *) echo JKS;; esac)
  tst=$(case "$ts" in *.p12|*.pkcs12) echo PKCS12;; *) echo JKS;; esac)

  # JAVA_HOME for nifi.sh
  grep -q '^export JAVA_HOME=' "$dir/bin/nifi-env.sh" \
    && sed -i "s|^export JAVA_HOME=.*|export JAVA_HOME=$LAB/jdk/$jdk|" "$dir/bin/nifi-env.sh" \
    || echo "export JAVA_HOME=$LAB/jdk/$jdk" >> "$dir/bin/nifi-env.sh"

  # heap
  sed -i -E "s|^java\.arg\.2=-Xms.*|java.arg.2=-Xms$HEAP|; s|^java\.arg\.3=-Xmx.*|java.arg.3=-Xmx$HEAP|" "$boot"

  common=(
    nifi.web.http.host= nifi.web.http.port=
    nifi.web.https.host=localhost nifi.web.https.port=$port
    nifi.remote.input.secure=true nifi.remote.input.socket.port= nifi.remote.input.host=localhost
    "nifi.security.keystore=$CREF/$(basename "$ks")" nifi.security.keystoreType=$kst
    nifi.security.keystorePasswd=$KEYSTORE_PASS nifi.security.keyPasswd=$KEYSTORE_PASS
    "nifi.security.truststore=$CREF/$(basename "$ts")" nifi.security.truststoreType=$tst
    nifi.security.truststorePasswd=$TRUSTSTORE_PASS
    nifi.security.user.authorizer=managed-authorizer
    nifi.security.user.login.identity.provider=
    nifi.sensitive.props.key=$SENSITIVE_PROPS_KEY
    nifi.state.management.embedded.zookeeper.start=false
  )
  # No Python extensions: an absent key disables the bridge (blank fails to start).
  case "$ver" in 2.*) common+=(-nifi.python.command)
    # 2.x bootstrap management server defaults to 127.0.0.1:52020 for every instance.
    $PY "$HERE/props.py" "$boot" "management.server.address=http://127.0.0.1:$((port + 34000))";;
  esac
  if [ "$proto" != "-" ]; then
    common+=(
      nifi.cluster.is.node=true nifi.cluster.protocol.is.secure=true
      nifi.cluster.node.address=localhost nifi.cluster.node.protocol.port=$proto
      nifi.cluster.load.balance.host=localhost nifi.cluster.load.balance.port=$lb
      nifi.cluster.flow.election.max.candidates=$(echo "$members" | wc -l)
      "nifi.cluster.flow.election.max.wait.time=1 mins"
      nifi.zookeeper.connect.string=localhost:$ZK_PORT nifi.zookeeper.root.node=$CLUSTER_ZK_ROOT
    )
    ids=(); for m in $members; do ids+=("$(node_dn "$(inst_field "$m" 5)")"); done
    write_authorizers "$conf/authorizers.xml" "${ids[@]}"
    sed -i -E "s|(<property name=\"Connect String\">)[^<]*(</property>)|\1localhost:$ZK_PORT\2|; s|(<property name=\"Root Node\">)[^<]*(</property>)|\1$CLUSTER_ZK_ROOT/state\2|" "$conf/state-management.xml"
  else
    common+=(nifi.cluster.is.node=false)
    write_authorizers "$conf/authorizers.xml"
  fi
  $PY "$HERE/props.py" "$conf/nifi.properties" "${common[@]}"
  if is_split "$n"; then
    # What nifi.properties names under ./conf (flow, archive, authorizers, state management, ...) is in the conf
    # directory now; the repositories and the local state are in the data directory.
    sed -i -E "s#^([a-z0-9.]+)=\./conf/#\1=$conf/#; s#^([a-z0-9.]+)=\./(flowfile|content|provenance|database)_repository#\1=$data/\2_repository#" "$conf/nifi.properties"
    sed -i -E "s#(<property name=\"Directory\">)\./state/local(</property>)#\1$data/state/local\2#" "$conf/state-management.xml"
  fi
done

# lab.sh needs these next to it.
if [ "$HERE" != "$LAB" ]; then cp "$HERE"/{lab.conf,lab.sh,setup.sh,grant.py,props.py,nginx.conf} "$LAB/"; chmod +x "$LAB"/*.sh; fi
log "done. Next: $LAB/lab.sh start && $LAB/lab.sh grant && $LAB/lab.sh status (and $LAB/lab.sh nginx start for Studio, P8)"
